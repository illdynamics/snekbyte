#!/usr/bin/env bash
# Idempotent, reproducible debug-APK build for SnekByte.
#
#   bash android-app/scripts/build-debug.sh
#
# Produces dist/android/snekbyte-debug.apk + dist/android/snekbyte-debug.apk.sha256
# and dist/android/build-receipt.txt.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
APP="$ROOT/android-app"
DIST="$ROOT/dist/android"

# ---------------------------------------------------------------------------
# 1. Locate a compatible JDK (Capacitor 7 / AGP 8.7 compile with Java 21).
#    Gradle 8.11.1 supports JDK 17-23, so JDK 21 is the pin.
# ---------------------------------------------------------------------------
java_major() {
  "$1/bin/javac" -version 2>&1 | awk '{
    for (i = 1; i <= NF; i++)
      if ($i ~ /^[0-9]+\.[0-9]+/) { split($i, a, "."); print a[1]; exit }
  }'
}

find_java() {
  local cand major
  for cand in \
    "$ROOT/.scratch-snakepwn6000/toolchain/jdk21/Contents/Home" \
    "${JAVA_HOME:-}" \
    "/Library/Java/JavaVirtualMachines/temurin-21.jdk/Contents/Home" \
    "/opt/homebrew/opt/openjdk@21/libexec/openjdk.jdk/Contents/Home" \
    "/usr/lib/jvm/java-21-openjdk"; do
    [ -n "$cand" ] || continue
    [ -x "$cand/bin/javac" ] || continue
    major="$(java_major "$cand" 2>/dev/null || echo 0)"
    # AGP 8.7 / Capacitor 7 compile with Java 21 source/target.
    if [ "$major" -ge 21 ]; then echo "$cand"; return 0; fi
  done
  return 1
}

JAVA_HOME_FOUND="$(find_java)" || {
  echo "ERROR: JDK 21 not found. Install Temurin 21 (https://adoptium.net) and set JAVA_HOME." >&2
  exit 1
}
export JAVA_HOME="$JAVA_HOME_FOUND"

# ---------------------------------------------------------------------------
# 2. Locate the Android SDK (platforms;android-35 + build-tools;35.0.0).
# ---------------------------------------------------------------------------
find_sdk() {
  if [ -n "${ANDROID_SDK_ROOT:-}" ] && [ -d "$ANDROID_SDK_ROOT/platforms/android-35" ]; then
    echo "$ANDROID_SDK_ROOT"; return 0
  fi
  if [ -n "${ANDROID_HOME:-}" ] && [ -d "$ANDROID_HOME/platforms/android-35" ]; then
    echo "$ANDROID_HOME"; return 0
  fi
  for cand in \
    "$ROOT/.scratch-snakepwn6000/toolchain/sdk" \
    "$HOME/Library/Android/sdk" \
    "/usr/local/share/android-sdk" \
    "/opt/android-sdk"; do
    if [ -d "$cand/platforms/android-35" ]; then echo "$cand"; return 0; fi
  done
  return 1
}

SDK="$(find_sdk)" || {
  echo "ERROR: Android SDK with platforms;android-35 not found. Install cmdline-tools and run:" >&2
  echo "  sdkmanager --install 'platform-tools' 'platforms;android-35' 'build-tools;35.0.0'" >&2
  exit 1
}
export ANDROID_HOME="$SDK"
export ANDROID_SDK_ROOT="$SDK"
printf 'sdk.dir=%s\n' "$SDK" > "$APP/android/local.properties"

# ---------------------------------------------------------------------------
# 3. Reproducible dependency install (pinned package-lock.json).
# ---------------------------------------------------------------------------
echo "==> npm ci"
( cd "$APP" && npm ci )

# ---------------------------------------------------------------------------
# 4. Stage the verbatim Nuxel PWA web assets (+ Android-only shell bridge).
# ---------------------------------------------------------------------------
echo "==> staging web assets"
bash "$APP/scripts/stage-web-assets.sh"

# Regenerate Android launcher/splash artwork if ImageMagick is present; the
# committed outputs are used otherwise (icons are part of the repo).
if command -v magick >/dev/null 2>&1; then
  echo "==> regenerating Android icons/splash"
  bash "$APP/scripts/generate-icons.sh"
else
  echo "==> ImageMagick not found; using committed Android icons/splash"
fi

# ---------------------------------------------------------------------------
# 5. Sync the Capacitor Android platform (copies www/ into the native project).
# ---------------------------------------------------------------------------
echo "==> cap sync android"
( cd "$APP" && npx cap sync android )

# ---------------------------------------------------------------------------
# 6. Build the debug APK.
# ---------------------------------------------------------------------------
# The Cordova compatibility config is regenerated by `cap sync` with a
# permissive allow-list; SnekByte ships no Cordova plugins, so remove the
# allow-list entry to keep the declared surface strictly local.
python3 - "$APP/android/app/src/main/res/xml/config.xml" <<'PY'
import sys
path = sys.argv[1]
with open(path, encoding="utf-8") as f:
    xml = f.read()
xml = xml.replace('<access origin="*" />', '').replace('  \n  \n', '\n')
with open(path, "w", encoding="utf-8", newline="\n") as f:
    f.write(xml)
PY

echo "==> gradlew :app:assembleDebug"
( cd "$APP/android" && ./gradlew --no-daemon :app:assembleDebug )

# ---------------------------------------------------------------------------
# 7. Stage the verified artifact into dist/.
# ---------------------------------------------------------------------------
mkdir -p "$DIST"
cp "$APP/android/app/build/outputs/apk/debug/app-debug.apk" "$DIST/snekbyte-debug.apk"
( cd "$DIST" && shasum -a 256 snekbyte-debug.apk > snekbyte-debug.apk.sha256 )

# Build receipt (environment-independent summary).
{
  echo "artifact: dist/android/snekbyte-debug.apk"
  echo "sha256:   $(cat "$DIST/snekbyte-debug.apk.sha256" | awk '{print $1}')"
  echo "built-at: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "java:     $("$JAVA_HOME/bin/java" -version 2>&1 | head -1)"
  echo "node:     $(node --version)"
  echo "sdk:      $SDK"
} > "$DIST/build-receipt.txt"

echo ""
echo "BUILD COMPLETE"
echo "  APK:   $DIST/snekbyte-debug.apk"
echo "  SHA-256: $(awk '{print $1}' "$DIST/snekbyte-debug.apk.sha256")"
